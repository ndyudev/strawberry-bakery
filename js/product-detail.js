// Tìm id sản phẩm trùng từ link
function findProductDetail(id) {
  for (let i = 0; i < listProduct.length; i++) {
    if (listProduct[i].id == id) {
      let element = listProduct[i];
      return element;
    }
  }
}

let productDetail = findProductDetail(id);
// Đõ dự liệu lên product detail
function fillProductDetail() {
  document.querySelector(".data-imgMain").innerHTML = `<img
                src="${productDetail.img[0]}"
                alt="Sweetin – Chocolate Ruby"
              />`;
  document.querySelector(".product_detail_title").innerText =
    productDetail.title;
  document.querySelector(".product_detail_price").innerText =
    productDetail.price.toLocaleString() + "đ";
}

fillProductDetail();

// Hiển thị sản phẩm liên quan

let relatedProductHtml = "";

function fillRelatedProduct() {
  let count = 0;
  for (let i = 0; i < listProduct.length && count < 3; i++) {
    if (
      listProduct[i].category === productDetail.category &&
      listProduct[i].id !== productDetail.id
    ) {
      count++;
      relatedProductHtml += `
        <div class="related-product">
          <div class="related-product__image">
            <img
              src="${listProduct[i].img[0]}"
              alt="${listProduct[i].title}"
            />
          </div>
          <div class="related-product__info">
            <h4>${listProduct[i].title}</h4>
            <div class="related-product__price">
              ${listProduct[i].price.toLocaleString()}₫
            </div>
          </div>
        </div>`;
    }
  }
  document.querySelector(".related-product-fill").innerHTML =
    relatedProductHtml;
}

fillRelatedProduct();
// Đỗ dữ liệu vào ảnh nhỏ
let thumbnailImagesHtml = "";

function fillThumbnailImages() {  
  // Tạo thumbnails từ array ảnh của sản phẩm hiện tại
  for (let i = 0; i < productDetail.img.length; i++) {
    thumbnailImagesHtml += `
      <div class="thumbnail">
        <img
          src="${productDetail.img[i]}"
          alt="${productDetail.title}"
          onclick="changeMainImage(this)"
        />
      </div>`;
  }

  document.querySelector(".fill-thumbnail-images").innerHTML =
    thumbnailImagesHtml;

  // Thêm active class cho thumbnail đầu tiên
  let parent = document.querySelector(".fill-thumbnail-images");
  let firstThumbnail = parent.children[0];
  if (firstThumbnail) {
    firstThumbnail.classList.add("active");
  }
}

fillThumbnailImages();
